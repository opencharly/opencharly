#!/usr/bin/env bash
# check-omarchy-eval-agents.sh — deterministic gate for the committed omarchy PR-eval
# pi agents (AGENTS.md R7; plan eval-omarchy-pi-plugin.md PR1/I6).
# The harness-parity script diffs only files identical-by-design with charly/; .pi is
# an umbrella-specific fork with no charly twin, so the agent layer gets its own gate.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
fail() { echo "FAIL: $*" >&2; exit 1; }

AGENTS=(.pi/agents/omarchy-config-oracle.md .pi/agents/omarchy-eval-runner.md .pi/agents/omarchy-eval-supervisor.md .pi/agents/omarchy-cold-reader.md .pi/agents/worker.md)

# 1. The unique agents must be tracked, never gitignored.
for f in "${AGENTS[@]}"; do
  [ -f "$f" ] || fail "missing agent file: $f"
  git check-ignore -q "$f" && fail "agent $f is gitignored — must be committed"
done
git ls-files --error-unmatch "${AGENTS[@]}" >/dev/null || fail "a unique agent is untracked"

# 2. The marketplace-STAGED agents must stay ignored (regenerated by /claude:plugin import).
git check-ignore -q .pi/agents/pi-claude-marketplace-charly-internals-pr-validator.md \
  || fail "marketplace-staged agents must stay gitignored"

# 3. Every unique agent must have parseable frontmatter: open ---, name/description/tools,
#    a closing ---, and no body text leaking into the frontmatter.
for f in "${AGENTS[@]}"; do
  [ "$(head -1 "$f")" = "---" ] || fail "$f: frontmatter must start with ---"
  [ "$(grep -c '^---$' "$f")" -ge 2 ] || fail "$f: missing closing ---"
  grep -q '^name:' "$f"        || fail "$f: missing name:"
  grep -q '^description:' "$f" || fail "$f: missing description:"
  grep -q '^tools:' "$f"       || fail "$f: missing tools:"
  t=$(grep -n '^tools:' "$f"   | head -1 | cut -d: -f1)
  c=$(grep -n '^---$' "$f"     | sed -n '2p' | cut -d: -f1)
  [ "$t" -lt "${c:-0}" ] || fail "$f: tools: line leaks past the closing ---"
done

echo "check-omarchy-eval-agents: OK — ${#AGENTS[@]} unique agents tracked + parseable, staged agents ignored"