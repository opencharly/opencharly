#!/usr/bin/env bash
# design-disposition.sh — render design/dulling-disposition.md from design/dulling.tsv.
#
# The ledger is the record; this is its readable face: one line per capability, saying what happens
# to it. It is GENERATED and the ledger control (scripts/design-ledger.sh) fails when it drifts from
# the ledger, so the table can never describe a state the ledger does not have (A.10).
#
# Usage: bash scripts/design-disposition.sh [<root>]   (writes to stdout)
set -euo pipefail
root="${1:-$PWD}"
dulling="$root/design/dulling.tsv"
[[ -f "$dulling" ]] || { echo "design-disposition: $dulling is missing" >&2; exit 2; }

printf '# Capability disposition\n\n'
printf 'Generated by `scripts/design-disposition.sh` from `design/dulling.tsv`; `scripts/design-ledger.sh`\n'
printf 'fails when this file and the ledger disagree (A.10).\n\n'
printf '| capability | verdict | action | what happens |\n|---|---|---|---|\n'
awk -F'\t' '
  BEGIN { OFS = "" }
  /^#/ || $1 == "capability" { next }
  {
    cap = $1; verdict = $5; action = $8; disp = ""
    gsub(/\|/, "\\|", cap)   # a capability name may contain a pipe; escape it or the row splits
    if (verdict == "sharp") disp = "kept whole"
    else if (action == "accept retirement") disp = "retired (A.9)"
    else if (action ~ /^amend /) { a = action; sub(/^amend /, "", a); disp = "owes " a }
    else if (action == "verify live") disp = "unsettled"
    else if (action == "none") disp = "—"
    else disp = action
    printf "| %s | %s | %s | %s |\n", cap, verdict, action, disp
  }' "$dulling"
